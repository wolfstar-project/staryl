import { fileURLToPath } from "node:url";
import { startSocialPoller } from "#social/registry";
import { Events } from "#types";
import { envParseInteger, envParseString } from "@wolfstar/env-utilities";
import { Client, container, definePlugin } from "@wolfstar/http-framework";
import { registerCommands } from "@wolfstar/shared-http-pieces";

/**
 * Forwards each request of the interactions server to the client as {@link Events.ServerRequest}.
 *
 * @remarks The client creates its server in `listen()`, after the pieces are loaded, so a listener cannot name the
 * server as its emitter. The listeners of the event decide themselves whether they run.
 */
const serverEvents = definePlugin({
	name: "Staryl-ServerEvents",
	postListen(client) {
		client.server.on("request", (request, response) =>
			client.emit(Events.ServerRequest, request, response),
		);
	},
});

export function createClient() {
	// The client registers itself as `container.client`:
	// oxlint-disable-next-line no-new
	new Client({
		api: {
			listenOptions: {
				port: envParseInteger("API_PORT"),
				host: envParseString("API_ADDRESS"),
			},
		},
		// The locales are copied next to the bundle by the tsdown `copyPlugin`, so the directory is resolved from the
		// build instead of the plugin default (`<root>/languages`):
		i18n: {
			defaultLanguageDirectory: fileURLToPath(
				new URL("../locales", import.meta.url),
			),
			defaultName: "en-US",
			defaultNS: "globals",
			defaultMissingKey: "globals:default",
			i18next: {
				returnNull: false,
				returnObjects: true,
				returnEmptyString: false,
			},
		},
		// Names the subcommand pieces `parent/group/sub`, so same-named files across groups (`twitch/add.ts` and a future
		// `kick/add.ts`) do not collide in the command store:
		subcommandsAdvanced: { nameCommandsAutogenerated: true },
		plugins: [serverEvents],
	});
}

export async function loadAll() {
	const { client } = container;
	await client.load();

	void registerCommands();

	// Starts the HTTP interactions endpoint, then the checks of the social sources:
	await client.listen({
		address: envParseString("HTTP_ADDRESS", "0.0.0.0"),
		port: envParseInteger("HTTP_PORT", 3000),
	});
	startSocialPoller();
}
